#!/usr/bin/env python3
"""Player-spawn scaffold parser/regenerator prototype (docs/re/player-spawn-generation.md).

Validates that the documented scaffold wire format (everything in the FA015807 body that is NOT the
ProtoCoreCharacterIIR) parses structurally and regenerates BYTE-EXACT across the capture set. This is the
go/no-go gate for the C# PlayerSpawnScaffold codec that retires the PlayerSpawnTemplate constant.

Body layout under test (offsets body-relative, Strie template):
  [0:20]   IIR header: bodyLen, subOp=FA015807, ack=C350, handle, fieldA
  [20:~66] transform group 0x2C: 0A vec3, 12 quat, (25 scale,) 18 playfield-varint
  [..]     pre block: small varint-ish bytes + zeros run (attribute scaffold, mostly zeros)
  @outer   u32 outerLen enclosing the rest
    [..]   scaffold-A (167b, near-constant)
    @inner u32 innerLen = ProtoCoreCharacterIIR length
    [..]   the CharacterIIR (opaque here - kept verbatim)
    [..]   scaffold-B: hdr 00000000 00000004; entry0 [2][3F1][v][B7][1.0];
           entries 1..6 [idx][0][u16 v][1.0]; entry 7 [7][0][f32 weight];
           feat entries [u32 idx][u32 0][u8 type][u8 sub][u32 value] (14b, idx ascending from 8?)
    [..]   tail: 01 2C header + ascending u40 ID list + 0003F1 00000000(?) 0003F1 sentinel

Usage:
  python3 tools/capture/parse_spawn_scaffold.py template          # dissect the C# PlayerSpawnTemplate bytes
  python3 tools/capture/parse_spawn_scaffold.py all               # try parse+regen every FA015807 in every capture
  python3 tools/capture/parse_spawn_scaffold.py one <cap> <idx>   # dissect one spawn verbosely
"""
import importlib.util
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent  # repo root (this file is at tools/capture/)

spec = importlib.util.spec_from_file_location('c', ROOT / 'tools/capture/compare_log_to_dump.py')
cdt = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cdt)


def template_bytes():
    # PlayerSpawnTemplate.cs was RETIRED (the player spawn is now DB-generated by PlayerSpawnScaffoldCodec),
    # so the old hardcoded-template compare modes no longer have a source. Degrade gracefully instead of
    # crashing: the capture-driven modes (all/players/one/dumpb) don't need it.
    src_file = ROOT / 'Faolan/GameServer/Spawn/PlayerSpawnTemplate.cs'
    if not src_file.exists():
        return None
    src = src_file.read_text()
    return bytes(int(h, 16) for h in re.findall(r'0x([0-9A-Fa-f]{2})', src.split('Bytes =')[1]))


def u32(b, i):
    return int.from_bytes(b[i:i + 4], 'big')


def hexd(b, start, end, width=16):
    for o in range(start, min(end, len(b)), width):
        row = b[o:min(o + width, end)]
        print(f'    {o:5} {row.hex(" ")}')


class ParseError(Exception):
    pass


def read_varint(b, i):
    v, shift = 0, 0
    while True:
        if i >= len(b):
            raise ParseError('varint eof')
        byte = b[i]
        v |= (byte & 0x7F) << shift
        i += 1
        shift += 7
        if not byte & 0x80:
            return v, i


def parse_player_spawn(b, verbose=False):
    """Structurally parse a player FA015807 body. Returns a dict of parts; regen() must rebuild b exactly."""
    p = {}
    if len(b) < 24 or u32(b, 4) != 0xFA015807:
        raise ParseError('not FA015807')
    p['bodyLen'] = u32(b, 0)
    if p['bodyLen'] != len(b) - 4:
        raise ParseError(f'bodyLen {p["bodyLen"]} != len-4 {len(b)-4}')
    p['ack'] = u32(b, 8)
    p['handle'] = u32(b, 12)
    p['fieldA'] = u32(b, 16)

    i = 20
    if b[i] != 0x2C:
        raise ParseError('no 0x2C transform group')
    i += 1
    # transform fields: 0A <len> vec3, 12 <len> quat, optional 25 <fixed32>, 18 <varint playfield>
    if b[i] != 0x0A:
        raise ParseError('no vec3')
    vlen = b[i + 1]
    p['vec3'] = b[i + 2:i + 2 + vlen]
    i += 2 + vlen
    if b[i] != 0x12:
        raise ParseError('no quat')
    qlen = b[i + 1]
    p['quat'] = b[i + 2:i + 2 + qlen]
    i += 2 + qlen
    p['scale'] = None
    if b[i] == 0x25:
        p['scale'] = b[i + 1:i + 5]
        i += 5
    if b[i] != 0x18:
        raise ParseError(f'no playfield varint at {i} (byte {b[i]:02x})')
    p['playfield'], i = read_varint(b, i + 1)

    p['preStart'] = i
    # Anchor the CharacterIIR (name-signature scan + its u32 length prefix); the pre-IIR region between the
    # transform and the IIR's length prefix (the zeros block, the outer length prefix when present, and
    # scaffold-A) is kept RAW for now - its internal structure is analyzed separately (cmd_compare).
    inner = find_character_iir(b)
    if inner is None:
        raise ParseError('CharacterIIR not found')
    iirOff, iirLen = inner
    p['iirOff'] = iirOff
    p['iirLen'] = iirLen
    p['iir'] = b[iirOff:iirOff + iirLen]
    if u32(b, iirOff - 4) != iirLen:
        raise ParseError('inner length prefix mismatch')
    p['preIir'] = b[p['preStart']:iirOff - 4]

    # everything after the CharacterIIR is one contiguous structured stream
    p['postIir'] = b[iirOff + iirLen:]
    parse_post_iir(p, p['postIir'], verbose)

    if verbose:
        dump(p, b)
    return p


def find_character_iir(b):
    """Find (offset, length) of the ProtoCoreCharacterIIR: 0A <namelen> <printable>, preceded by u32 len."""
    for i in range(24, len(b) - 2):
        if b[i] != 0x0A:
            continue
        n = b[i + 1]
        if not (1 <= n <= 63) or i + 2 + n > len(b):
            continue
        if not all(0x20 <= c <= 0x7E for c in b[i + 2:i + 2 + n]):
            continue
        L = u32(b, i - 4)
        if L < n + 2 or i + L > len(b):
            continue
        return i, L
    return None


def parse_post_iir(p, post, verbose=False):
    """Unified post-CharacterIIR stream (scaffold-B + tail, contiguous; retail's outer length prefix does
    NOT align with it):
      header  [u32 0][u32 4]
      entry0  [u32 2][u32 0x3F1][u32 count][u32 X]  (+ [f32 1.0] iff count > 0)
      count entries, uniform 14B: [u32 idx][u32 0][6B payload]
      iff count > 0: ID list of 5B groups [u8 val][u32 id], ascending, terminated by the group with id 0x3F1;
      iff count == 0: a bare [u32 0x3F1] terminator instead
      ending  [u32 N][N x (u32 id, s32 value)][u32 0][u32 0x3F1]
    """
    i = 0
    if u32(post, 0) != 0 or u32(post, 4) != 4:
        raise ParseError(f'post-IIR header {post[:8].hex()}')
    if u32(post, 8) != 2:
        raise ParseError(f'entry0 intro {post[8:16].hex()}')
    # The second field is 0x3F1 * (buffRecordCount + 1): 0x3F1 = none; each active buff/timer adds a
    # 60-byte record [t0][0x7E2][0][0x1207CF][a][b][0][seq][0xC350][handle][5x0] before the entry table.
    key = u32(post, 12)
    if key == 0 or key % 0x3F1 != 0:
        raise ParseError(f'entry0 key {key:#x} not a multiple of 0x3F1')
    n_buffs = key // 0x3F1 - 1
    i = 16
    buffs = []
    for _ in range(n_buffs):
        rec = post[i:i + 60]
        if len(rec) != 60 or u32(rec, 32) != 0xC350:
            raise ParseError(f'buff record {rec[:16].hex()}')
        buffs.append(rec)
        i += 60
    p['buffRecords'] = buffs
    count = u32(post, i)
    p['entry0X'] = u32(post, i + 4)
    i += 8
    if count > 0:
        if u32(post, i) != 0x3F800000:
            raise ParseError(f'entry0 weight {post[i:i+4].hex()}')
        i += 4
    entries = []
    for n in range(count):
        idx = u32(post, i)
        if u32(post, i + 4) != 0:
            raise ParseError(f'entry[{n}] zero field {post[i:i+14].hex()}')
        entries.append((idx, post[i + 8:i + 14]))
        i += 14
    p['entries'] = entries

    ids = []
    if count > 0:
        while True:
            if i + 5 > len(post):
                raise ParseError('id list ran off the end')
            val = post[i]
            ident = u32(post, i + 1)
            i += 5
            if ident == 0x3F1:
                if val != 0:
                    raise ParseError(f'id-list terminator with val {val:02x}')
                break
            ids.append((val, ident))
    else:
        if u32(post, i) != 0x3F1:
            raise ParseError(f'bare terminator {post[i:i+4].hex()}')
        i += 4
    p['idList'] = ids
    if any(b[1] < a[1] for a, b in zip(ids, ids[1:])):
        raise ParseError('id list not ascending')

    # ending: two count-prefixed [u32 id][u32 value] pair lists, then the final 0x3F1 marker.
    p['endPairs'], i = read_pair_list(post, i)
    p['endPairs2'], i = read_pair_list(post, i)
    if u32(post, i) != 0x3F1:
        raise ParseError(f'final marker {post[i:i+4].hex()}')
    i += 4
    if i != len(post):
        raise ParseError(f'post-IIR trailing {len(post)-i} bytes: {post[i:i+16].hex()}')


def read_pair_list(b, i):
    n = u32(b, i)
    i += 4
    if n > 0x100:
        raise ParseError(f'implausible pair-list count {n:#x}')
    pairs = []
    for _ in range(n):
        pairs.append((u32(b, i), u32(b, i + 4)))
        i += 8
    return pairs, i


def regen(p):
    """Rebuild the body byte-exact from the parsed parts."""
    out = bytearray()
    out += p['bodyLen'].to_bytes(4, 'big')
    out += (0xFA015807).to_bytes(4, 'big')
    out += p['ack'].to_bytes(4, 'big')
    out += p['handle'].to_bytes(4, 'big')
    out += p['fieldA'].to_bytes(4, 'big')
    out += b'\x2c\x0a' + bytes([len(p['vec3'])]) + p['vec3']
    out += b'\x12' + bytes([len(p['quat'])]) + p['quat']
    if p['scale'] is not None:
        out += b'\x25' + p['scale']
    out += b'\x18' + write_varint(p['playfield'])
    out += p['preIir']
    out += p['iirLen'].to_bytes(4, 'big')
    out += p['iir']
    out += regen_post_iir(p)
    return bytes(out)


def regen_post_iir(p):
    out = bytearray()
    out += b'\x00\x00\x00\x00\x00\x00\x00\x04'
    count = len(p['entries'])
    out += (2).to_bytes(4, 'big') + (0x3F1 * (len(p['buffRecords']) + 1)).to_bytes(4, 'big')
    for rec in p['buffRecords']:
        out += rec
    out += count.to_bytes(4, 'big') + p['entry0X'].to_bytes(4, 'big')
    if count > 0:
        out += (0x3F800000).to_bytes(4, 'big')
    for idx, payload in p['entries']:
        out += idx.to_bytes(4, 'big') + b'\x00' * 4 + payload
    if count > 0:
        for val, ident in p['idList']:
            out += bytes([val]) + ident.to_bytes(4, 'big')
        out += b'\x00' + (0x3F1).to_bytes(4, 'big')
    else:
        out += (0x3F1).to_bytes(4, 'big')
    for pairs in (p['endPairs'], p['endPairs2']):
        out += len(pairs).to_bytes(4, 'big')
        for ident, val in pairs:
            out += ident.to_bytes(4, 'big') + val.to_bytes(4, 'big')
    out += (0x3F1).to_bytes(4, 'big')
    return bytes(out)


def write_varint(v):
    out = bytearray()
    while True:
        b7 = v & 0x7F
        v >>= 7
        if v:
            out.append(b7 | 0x80)
        else:
            out.append(b7)
            return bytes(out)


def dump(p, b):
    print(f"  handle=0x{p['handle']:X} fieldA=0x{p['fieldA']:X} len={len(b)} playfield={p['playfield']}")
    print(f"  preStart={p['preStart']} iirOff={p['iirOff']} iirLen={p['iirLen']} preIir={len(p['preIir'])}b postIir={len(p['postIir'])}b")
    print(f"  preIir ({len(p['preIir'])}b):")
    hexd(p['preIir'], 0, len(p['preIir']))
    print(f"  entry0X={p['entry0X']:#x} count={len(p['entries'])}")
    for idx, payload in p['entries']:
        print(f"    entry idx={idx:#04x} payload={payload.hex(' ')}")
    print(f"  idList ({len(p['idList'])}):")
    for val, ident in p['idList']:
        print(f"    id={ident:#08x} ({ident}) val={val:#04x}")
    for key in ('endPairs', 'endPairs2'):
        print(f"  {key} ({len(p[key])}):")
        for ident, val in p[key]:
            sval = val - 0x100000000 if val >= 0x80000000 else val
            print(f"    id={ident} value={sval}")


def receiver_instance(receiver_hex):
    """ProtoEndpoint { 0D <fixed32 type>, 10 <varint instance> } -> instance."""
    b = bytes.fromhex(receiver_hex)
    i = 0
    while i < len(b):
        if b[i] == 0x0D:
            i += 5
        elif b[i] == 0x10:
            v, _ = read_varint(b, i + 1)
            return v
        else:
            return None
    return None


def spawns_in_capture(cap, player_only=False):
    out = []
    try:
        for pkt in cdt.from_dump(str(cap)):
            if pkt[2] == 0x2000 and len(pkt[4]) >= 16 and pkt[4][4:8].hex() == 'fa015807':
                if player_only:
                    inst = receiver_instance(pkt[1])
                    if inst is None or u32(pkt[4], 12) != inst:
                        continue
                out.append(pkt[4])
    except Exception as e:
        print(f'  [warn] {cap.name}: {e}')
    return out


def cmd_template():
    b = template_bytes()
    if b is None:
        print('PlayerSpawnTemplate.cs was retired (player spawn is now DB-generated by PlayerSpawnScaffoldCodec).')
        print("Nothing to compare against. Use a capture-driven mode instead: 'all', 'players', 'one <cap> <handle>'.")
        return
    print(f'PlayerSpawnTemplate: {len(b)} bytes')
    p = parse_player_spawn(b, verbose=True)
    r = regen(p)
    print(f'  regen byte-exact: {r == b}')
    if r != b:
        for i in range(min(len(r), len(b))):
            if r[i] != b[i]:
                print(f'  first diff @{i}: orig {b[i:i+16].hex()} regen {r[i:i+16].hex()}')
                break


def cmd_all(player_only=False):
    caps = sorted((ROOT / 'Captures').glob('*.tshark.json'))
    total = ok = 0
    fails = {}
    for cap in caps:
        for idx, body in enumerate(spawns_in_capture(cap, player_only)):
            total += 1
            try:
                p = parse_player_spawn(body)
                if regen(p) == body:
                    ok += 1
                else:
                    fails.setdefault('regen-mismatch', []).append((cap.name, idx, len(body)))
            except ParseError as e:
                fails.setdefault(str(e).split(' at ')[0][:40], []).append((cap.name, idx, len(body)))
            except Exception as e:
                fails.setdefault(f'EXC {type(e).__name__}: {e}'[:60], []).append((cap.name, idx, len(body)))
    print(f'parsed+regen byte-exact: {ok}/{total}')
    for reason, items in sorted(fails.items(), key=lambda kv: -len(kv[1])):
        print(f'  [{len(items):4}] {reason}  e.g. {items[0]}')


def cmd_one(cap, idx):
    body = spawns_in_capture(Path(cap), player_only=True)[int(idx)]
    try:
        p = parse_player_spawn(body, verbose=True)
        r = regen(p)
        print(f'  regen byte-exact: {r == body}')
    except ParseError as e:
        print(f'  PARSE FAIL: {e}')
        print(f'  full body ({len(body)}b):')
        hexd(body, 0, len(body))


def cmd_pre():
    """Compare the pre-IIR region across all parseable player spawns: length, outer-prefix location/value,
    and which bytes vary vs the template."""
    ref = None
    rows = []
    _tb = template_bytes()
    caps = [(Path('TEMPLATE'), [_tb])] if _tb is not None else []
    caps += [(cap, spawns_in_capture(cap, player_only=True)) for cap in sorted((ROOT / 'Captures').glob('*.tshark.json'))]
    for cap, bodies in caps:
        for idx, body in enumerate(bodies):
            try:
                p = parse_player_spawn(body)
            except ParseError:
                continue
            pre = p['preIir']
            # locate the outer length prefix inside pre: a u32 at pre-offset o whose value spans past the IIR
            # into the post-IIR region: preStart + o + 4 + value == an end E with iirEnd <= E <= len(body)
            iir_end = p['iirOff'] + p['iirLen']
            outer = []
            for o in range(0, len(pre) - 3):
                val = u32(pre, o)
                e = p['preStart'] + o + 4 + val
                if val > 0 and iir_end <= e <= len(body):
                    outer.append((o, val, e - iir_end, len(body) - e))
            name = p['iir'][2:2 + p['iir'][1]].decode('ascii', 'replace')
            rows.append((cap.name[:40], idx, name, len(body), len(pre), outer, pre))
    print(f'{len(rows)} parseable player spawns')
    for capname, idx, name, blen, plen, outer, pre in rows:
        o_str = ' '.join(f'@{o}={v}(postIn={pi},rest={r})' for o, v, pi, r in outer[:3])
        print(f'  {capname:42} #{idx} {name:14} len={blen:5} pre={plen:3} outer: {o_str}')
    # byte-variance vs the longest common pre length
    if rows:
        ref = rows[0][6]
        same_len = [r[6] for r in rows if len(r[6]) == len(ref)]
        print(f'\npre-IIR variance among {len(same_len)} spawns with pre len {len(ref)}:')
        for o in range(len(ref)):
            vals = {pre[o] for pre in same_len}
            if len(vals) > 1:
                print(f'  pre[{o:3}] varies: {sorted(f"{v:02x}" for v in vals)}')


def cmd_prediff():
    """Group player-spawn pre-IIR regions by length and show, per group, every distinct byte column."""
    groups = {}
    _tb = template_bytes()
    caps = [(Path('TEMPLATE'), [_tb])] if _tb is not None else []
    caps += [(cap, spawns_in_capture(cap, player_only=True)) for cap in sorted((ROOT / 'Captures').glob('*.tshark.json'))]
    for cap, bodies in caps:
        for idx, body in enumerate(bodies):
            try:
                p = parse_player_spawn(body)
            except ParseError:
                continue
            name = p['iir'][2:2 + p['iir'][1]].decode('ascii', 'replace')
            groups.setdefault(len(p['preIir']), []).append((name, p['preIir']))
    for plen, items in sorted(groups.items()):
        names = sorted({n for n, _ in items})
        print(f'== pre len {plen} ({len(items)} spawns: {", ".join(names)})')
        ref = items[0][1]
        varying = [o for o in range(plen) if len({pre[o] for _, pre in items}) > 1]
        print(f'   varying offsets: {varying}')
        # print the distinct values per varying run
        runs = []
        for o in varying:
            if runs and o == runs[-1][-1] + 1:
                runs[-1].append(o)
            else:
                runs.append([o])
        for run in runs:
            vals = {(n, bytes(pre[run[0]:run[-1] + 1]).hex()) for n, pre in items}
            uniq = {}
            for n, v in sorted(vals):
                uniq.setdefault(v, set()).add(n)
            print(f'   run {run[0]}..{run[-1] + 1} (abs {run[0] + 65}..{run[-1] + 66}):')
            for v, ns in sorted(uniq.items()):
                print(f'     {v} <- {", ".join(sorted(ns))}')
        # constant skeleton: hex with XX for varying
        skel = ''.join('XX' if o in set(varying) else f'{ref[o]:02x}' for o in range(plen))
        print(f'   skeleton: {skel}')


def cmd_dumpb(cap, idx):
    """Dump everything after the CharacterIIR raw (scaffold-B + tail), plus the pre/scaffold-A regions."""
    body = spawns_in_capture(Path(cap), player_only=True)[int(idx)]
    inner = find_character_iir(body)
    if inner is None:
        print('CharacterIIR not found')
        return
    iirOff, iirLen = inner
    end = iirOff + iirLen
    print(f'len={len(body)} iirOff={iirOff} iirLen={iirLen} postIir={len(body)-end}b')
    name_len = body[iirOff + 1]
    print(f'name={body[iirOff+2:iirOff+2+name_len].decode("ascii", "replace")}')
    print('pre+scaffoldA [20:iirOff-4]:')
    hexd(body, 20, iirOff - 4)
    print('post-IIR:')
    hexd(body, end, len(body))


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'template'
    if cmd == 'template':
        cmd_template()
    elif cmd == 'all':
        cmd_all()
    elif cmd == 'players':
        cmd_all(player_only=True)
    elif cmd == 'one':
        cmd_one(sys.argv[2], sys.argv[3])
    elif cmd == 'dumpb':
        cmd_dumpb(sys.argv[2], sys.argv[3])
    elif cmd == 'pre':
        cmd_pre()
    elif cmd == 'prediff':
        cmd_prediff()
