using System;
using System.Threading.Tasks;
using Faolan.Core.Network;
using Faolan.Core.Network.Packets;
using Faolan.Core.Network.Packets.Opcodes;

// ReSharper disable once CheckNamespace
namespace Faolan.GameServer
{
	public partial class GameServerListener
	{
		private async Task MapChange(INetworkClient client)
		{
			await new PacketStream().WriteHeader(LoginWorldSender, LoginWorldReceiver(client), 0x00002000).WriteArrayUInt32Length(s =>
				s.WriteUInt32(GameServer0X2000RespondsOpcodes.MapChange).WriteUInt32(0).WriteUInt32(0).WriteByte(0).WriteVector3(client.Session.Character.Position).WriteByte(0x62).WriteUInt32(0x0000C79C)
					.WriteUInt32(client.Session.Character.MapId ?? throw new Exception("client.Character.MapId == null")).WriteArray(0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
						0x00, 0x00, 0x9C, 0x50, 0x00, 0x34, 0x34, 0x8C, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x18, 0x00, 0x00, 0x00, 0x01, 0x00, 0x34, 0x34, 0x8C, 0x00, 0x00, 0xCB, 0x20, 0x41, 0x70, 0x00, 0x00, 0x3E,
						0xF2, 0x95, 0x73, 0x00, 0x00, 0x00, 0x03, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x07, 0x00, 0x00, 0x00, 0x01)).SendAsync(client);
		}
	}
}
