	// Constructs the character-create EDITOR avatar record - the SimpleCharFullUpdate (FA015807) the editor
	// streams for the player's preview pedestal (issue #189, decoded in docs/create-editor-bursts.md). It is an
	// ordinary entity spawn of the chosen looks: the SAME grammar as the login/world-entry player spawn, so it
	// reuses SpawnPacketBuilder (the typed ProtoVec3/ProtoQuat transform + the ProtoCoreCharacterIIR round-trip)
	// rather than a bespoke decoder. The whole record is reconstructed:
	//   - the TRANSFORM from the typed pose,
	//   - the IDENTITY/APPEARANCE by decoding the template's ProtoCoreCharacterIIR and re-encoding it (a
	//     byte-identical round-trip, verified by CreateEditorAvatarTests) - this is the seam where the create
	//     flow's live chosen looks will be substituted (override the decoded message's fields),
	// and the two live-session values are parameterized:
	//   - the entity HANDLE (the editor scene handle), and
	//   - the per-session PLAYFIELD INSTANCE carried in the transform's `18 <varint>` (the same token the
	//     PlayfieldFIIR MapChange advertises) - rewritten in place over the template's.
	// The avatar's POSE is fixed (the editor always spawns it on the same pedestal - byte-identical across all
	// seven create captures). Building from the captured handle + playfield + template looks reproduces the
	// captured record byte-for-byte (CreateEditorAvatarTests, against the SpawnEditorAvatar golden lifted from
	// the InitialBurst capture).
	public static class CreateEditorAvatarBuilder
	{
		// The fixed editor pedestal pose (docs/create-editor-bursts.md): byte-identical in every create capture.
		public static readonly Vector3 PedestalPosition = new(262.931f, 6.014f, 280.970f);
		public static readonly Quaternion PedestalRotation = new(0f, 0.98769f, 0f, 0.15643f); // ~18 deg about Y

		// The editor scene handle the avatar is addressed to (constant across captures - a scene-local handle, not
		// the player's character id) and the captured session playfield instance (= the MapChange token), used by
		// the oracle test and as the create-flow default until a live token is allocated for the editor session.
		public const uint EditorAvatarHandle = 0x0009FF92;
		public const uint EditorPlayfieldInstance = 0x00502276;

		// Offset of the playfield-instance varint inside the FA015807 body (the Iir-carrier payload, i.e. the
		// record minus its [u32 len][u32 iirType] prefix): [C350][handle][fieldA] 2C 0A0F<vec3 15> 1214<quat 20>
		// 18 <varint>. = 12 + 1 + 2 + 15 + 2 + 20 + 1 = 53. Session tokens are 4-byte LEB128 varints, so the
		// length is stable and the rewrite is splice-free.
		private const int BodyPlayfieldVarintOffset = 53;

		// The captured editor-avatar record ([u32 len][u32 FA015807][body]) - the construction base it decodes the
		// looks ("Stygian Female" ProtoCoreCharacterIIR) and transform pose from. Lazily built so it follows
		// AvatarBody's initialization regardless of field declaration order.
		private static byte[] _template;
		private static byte[] Template => _template ??= BuildTemplate();

		// Builds the Iir-carrier body (the bytes after the carrier's [u32 len][u32 iirType] prefix) for the editor
		// avatar, addressed to `handle` with the session `playfieldInstance` spliced into the transform. The
		// transform is reconstructed from the typed pose (read from the template so the floats re-encode exactly)
		// and the identity from the template's decoded CharacterIIR (re-encoded - the substitution seam for live
		// chosen looks). Pass the captured handle + EditorPlayfieldInstance to reproduce the capture byte-for-byte.
		public static byte[] BuildBody(uint handle, uint playfieldInstance)
		{
			return BuildBody(handle, playfieldInstance, TemplateLooks());
		}

		// As BuildBody, with the avatar's looks supplied by the caller (the create flow's chosen looks). The looks
		// must be a ProtoCoreCharacterIIR; on resize SpawnPacketBuilder delta-adjusts the surrounding length fields.
		public static byte[] BuildBody(uint handle, uint playfieldInstance, ProtoCoreCharacterIIR looks)
		{
			var record = SpawnPacketBuilder.BuildSpawn(Template, handle, PedestalPositionOf(Template), PedestalRotationOf(Template), looks);
			var body = record[8..]; // drop the [u32 len][u32 FA015807] carrier prefix the Iir() helper re-adds
			WritePlayfieldInstance(body, playfieldInstance);
			return body;
		}

		// The "Stygian Female" looks decoded from the captured template - the default until the create flow threads
		// the player's chosen looks through.
		private static ProtoCoreCharacterIIR TemplateLooks()
		{
			if (!PlayerSpawnReader.TryReadCharacterMessage(Template[8..], out var read))
				throw new InvalidOperationException("editor-avatar template has no decodable CharacterIIR");
			return read.Message;
		}

		// The avatar's pose, read from the template's transform floats (little-endian) so the reconstructed
		// ProtoVec3/ProtoQuat re-encode byte-identically. PedestalPosition/PedestalRotation document the values.
		private static Vector3 PedestalPositionOf(byte[] record)
		{
			return new Vector3(
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.PosXOffset, 4)),
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.PosYOffset, 4)),
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.PosZOffset, 4)));
		}

		private static Quaternion PedestalRotationOf(byte[] record)
		{
			return new Quaternion(
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.RotXOffset, 4)),
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.RotYOffset, 4)),
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.RotZOffset, 4)),
				BinaryPrimitives.ReadSingleLittleEndian(record.AsSpan(SpawnPacketBuilder.RotWOffset, 4)));
		}

		// Overwrites the 4-byte playfield-instance varint in place. Session tokens live in [2^21, 2^28) so they
		// always encode to exactly 4 LEB128 bytes - keeping the surrounding framing (the 0x2C group length, the
		// body length) untouched. Guarded so an out-of-range token fails loudly instead of corrupting the frame.
		private static void WritePlayfieldInstance(byte[] body, uint value)
		{
			if (value is < (1u << 21) or >= (1u << 28))
				throw new ArgumentOutOfRangeException(nameof(value),
					$"playfield instance 0x{value:X} does not encode to a 4-byte varint");

			body[BodyPlayfieldVarintOffset + 0] = (byte)(0x80 | (value & 0x7F));
			body[BodyPlayfieldVarintOffset + 1] = (byte)(0x80 | ((value >> 7) & 0x7F));
			body[BodyPlayfieldVarintOffset + 2] = (byte)(0x80 | ((value >> 14) & 0x7F));
			body[BodyPlayfieldVarintOffset + 3] = (byte)((value >> 21) & 0x7F);
		}

		private static byte[] BuildTemplate()
		{
			// The avatar's Iir body, lifted verbatim from the create-no-worldenter capture (RetailCreateEditorInitialBurst
			// row at handle 0x0009FF92, locked by InitialBurst.bin). Only the looks blob is consumed from it.
			var body = AvatarBody;
			var record = new byte[8 + body.Length];
			BinaryPrimitives.WriteUInt32BigEndian(record.AsSpan(0, 4), (uint)(4 + body.Length));
			BinaryPrimitives.WriteUInt32BigEndian(record.AsSpan(4, 4), 0xFA015807u);
			body.CopyTo(record, 8);
			return record;
		}

