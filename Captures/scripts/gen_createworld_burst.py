#!/usr/bin/env python3
"""Generate constructive PacketStream C# for the hoxxling create-world burst (:7012 S->C),
grouped into the 6 chunks, substituting the captured char instance with `id`.

Reads the canonical Captures/*.tshark.json dump (already de-framed: endpoint class ids + opcode + body are
fields), reconstructing each ProtoEndpoint header blob from its class id + instance.

NOTE: the committed Faolan/GameServer/CreateFlow/RetailCreateWorldEntryBurst.cs has since been hand-refactored
(ConanEndpoints.EndpointBytes + named opcodes), so this generator's raw-byte output is SUPERSEDED — re-running
it would revert those edits. It writes to an explicit output path (default /tmp) so it never clobbers the
refactored file; pass the .cs path as argv[1] only if you really intend to regenerate the verbatim form."""
import json, struct, sys, os

CAP='Captures/Hoxxling_mage-heraldofxotli_create_modified_all_sliders-very_long_loading_screen-chat_message_before_exit.tshark.json'
OUT=sys.argv[1] if len(sys.argv)>1 else '/tmp/RetailCreateWorldEntryBurst.cs'
INST=0x01316E71

def varint(v):
    out=bytearray()
    while True:
        b=v&0x7f; v>>=7
        out.append(b|(0x80 if v else 0))
        if not v: break
    return bytes(out)
INST_VAR=varint(INST)
INST_RAW=struct.pack('>I',INST)

def u32(b,o): return struct.unpack('>I',b[o:o+4])[0]

def endpoint_blob(cls_hex, inst_hex):
    """Rebuild the on-wire ProtoEndpoint header blob [0x0d <classId LE32> (0x10 <instance varint>)?] from the
    dump's parsed class id + instance (the .tshark.json de-frames the header into these fields)."""
    blob=bytes([0x0d])+struct.pack('<I',int(cls_hex,16))
    if inst_hex is not None:
        blob+=bytes([0x10])+varint(int(inst_hex,16))
    return blob

def body_of(p): return bytes.fromhex(p.get('BodyHex') or '')

def tok(body):
    if bytes.fromhex('A36D3B74') not in body: return None
    j=body.find(bytes.fromhex('A36D3B74'))
    while j<len(body)-1:
        if body[j]==0x22:
            ln=body[j+1]
            if 0<ln<40 and j+2+ln<=len(body):
                s=body[j+2:j+2+ln]
                if all(32<=c<127 for c in s): return s.decode()
        j+=1
    return None

pk=json.load(open(CAP))['Packets']
w=[p for p in pk if p['Source']['Port']==7012 or p['Destination']['Port']==7012]

# group S->C into chunks at client triggers
triggers={'ClientLoadingDone','StartScript','Move','IntroDone'}
chunks=[[]]
seen_hello=False
for p in w:
    cs=p['Source']['Port']!=7012   # client->server (upload to the :7012 world server)
    if cs:
        if (p.get('Opcode') or '').lower()=='0x2003': seen_hello=True; continue
        if seen_hello and tok(body_of(p)) in triggers: chunks.append([])
    elif seen_hello:
        chunks[len(chunks)-1].append(p)

def hexlist(bs): return ", ".join(f"0x{b:02X}" for b in bs)

def emit_packet(p):
    sender=endpoint_blob(p['SenderClass'], p.get('SenderInstance'))
    receiver=endpoint_blob(p['ReceiverClass'], p.get('ReceiverInstance'))
    opcode=int(p['Opcode'],16)
    headerdata=bytes.fromhex((p.get('HeaderExtraHex') or '').replace(' ',''))
    body=body_of(p)
    # receiver: if ends with INST_VAR use AppendVarint
    if receiver.endswith(INST_VAR):
        recv=f"AppendVarint([{hexlist(receiver[:-len(INST_VAR)])}], id)"
    else:
        recv=f"[{hexlist(receiver)}]"
    hd = f", [{hexlist(headerdata)}]" if headerdata else ""
    # body: split on raw INST -> WriteUInt32(id)
    parts=[]; i=0; cur=bytearray()
    while i < len(body):
        if body[i:i+4]==INST_RAW:
            if cur: parts.append(("arr",bytes(cur))); cur=bytearray()
            parts.append(("id",None)); i+=4
        else:
            cur.append(body[i]); i+=1
    if cur: parts.append(("arr",bytes(cur)))
    chain=f"new PacketStream().WriteHeader([{hexlist(sender)}], {recv}, 0x{opcode:04X}{hd})"
    for kind,val in parts:
        if kind=="id": chain+=".WriteUInt32(id)"
        else: chain+=f".WriteArray({hexlist(val)})"
    return chain+".SendAsync(client)"

# (The old byte-identity self-test compared a rebuilt raw frame against the original RawBytesBase64; the
# .tshark.json dump is already de-framed, so there is no raw frame to round-trip — the header blobs are
# reconstructed from the parsed class+instance fields above.)

def pkt_lines(chunk, indent):
    lines=[]
    for p in chunk:
        lines.append(indent+"await "+emit_packet(p)+";")
    return lines

L=[]
L.append("using System.Threading.Tasks;")
L.append("using Faolan.Core.Network;")
L.append("using Faolan.Core.Network.Packets;")
L.append("")
L.append("namespace Faolan.GameServer")
L.append("{")
L.append("\tpublic partial class GameServerListener")
L.append("\t{")
L.append("\t\t// AUTO-GENERATED by Captures/scripts/gen_createworld_burst.py from")
L.append("\t\t// "+CAP.split('/')[-1])
L.append("\t\t// The post-creation WORLD entry (intro cutscene: shipwreck/drowning -> beach -> Kalanthes ->")
L.append("\t\t// ApproachCasilda), captured from the hoxxling world connection (:7012). Every reference to the")
L.append(f"\t\t// captured character instance 0x{INST:08X} is written as the live client instance `id`; NPC/dynel")
L.append("\t\t// handles (e.g. Kalanthes 0x000535A0... actually capture-specific) are kept verbatim so each")
L.append("\t\t// spawn handle stays consistent with the scry message that binds it. Delivered to match retail's")
L.append("\t\t// pacing: chunk 0 (SCENE) on the world Hello, then one chunk per client cutscene trigger")
L.append("\t\t// (ClientLoadingDone, StartScript, StartScript, Move, IntroDone).")
L.append(f"\t\t// Chunk S->C packet counts: {[len(c) for c in chunks]}.")
L.append("")
L.append("\t\tprivate async Task SendCreateWorldSceneBurst(INetworkClient client)")
L.append("\t\t{")
L.append("\t\t\tvar id = client.Session.Account.ClientInstance;")
L+=pkt_lines(chunks[0], "\t\t\t")
L.append("\t\t}")
L.append("")
L.append("\t\tprivate async Task SendNextCreateWorldChunk(INetworkClient client)")
L.append("\t\t{")
L.append("\t\t\tvar id = client.Session.Account.ClientInstance;")
L.append("\t\t\t// One chunk per client cutscene trigger, in order: ClientLoadingDone, StartScript,")
L.append("\t\t\t// StartScript, Move, IntroDone.")
L.append("\t\t\tswitch (client.Session.CreateWorldChunkIndex++)")
L.append("\t\t\t{")
for ci in range(1,6):
    L.append(f"\t\t\t\tcase {ci-1}:")
    if chunks[ci]:
        L+=pkt_lines(chunks[ci], "\t\t\t\t\t")
    L.append("\t\t\t\t\tbreak;")
L.append("\t\t\t}")
L.append("\t\t}")
L.append("\t}")
L.append("}")
open(OUT,'w').write("\n".join(L)+"\n")
print("chunks:", [len(c) for c in chunks], "total", sum(len(c) for c in chunks))
print(f"wrote {OUT} lines: {len(L)}")

